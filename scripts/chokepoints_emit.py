#!/usr/bin/env python3
"""Compile the chokepoint score TSV into a Zig constant table.

The scores are save-local: `system_id` only means something for the save whose
sha256 is passed as `--save-sha`. Regenerate the table (and change the sha)
whenever the campaign save changes; `--check` is the drift fence that keeps
`src/dll/c2/chokepoint_table.zig` byte-identical to the TSV.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

HEADER = (
    "system_id\tdegree\tbetweenness\tbetweenness_norm\tscore"
    "\tis_articulation\tis_bridge_endpoint"
)
TIER1_MIN = 100
TIER2_MIN = 200
SCORES_PER_LINE = 16


class ChokepointDataError(ValueError):
    """The TSV or the requested output does not satisfy the table contract."""


def _uint_field(raw: str, line_no: int, name: str) -> int:
    if not raw.isdigit():
        raise ChokepointDataError(
            f"line {line_no}: {name} is not a non-negative integer: {raw!r}"
        )
    return int(raw)


def parse_scores(text: str) -> list[int]:
    lines = text.splitlines()
    if not lines or lines[0] != HEADER:
        raise ChokepointDataError(
            "line 1: header does not match the seven-column chokepoint schema"
        )
    scores: list[int] = []
    for line_no, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        fields = line.split("\t")
        if len(fields) != 7:
            raise ChokepointDataError(
                f"line {line_no}: expected 7 tab fields, got {len(fields)}"
            )
        row_id = _uint_field(fields[0], line_no, "system_id")
        if row_id != len(scores):
            raise ChokepointDataError(
                f"line {line_no}: system_id {row_id} is not the expected {len(scores)}"
            )
        score = _uint_field(fields[4], line_no, "score")
        if score > 65535:
            raise ChokepointDataError(f"line {line_no}: score {score} exceeds u16")
        scores.append(score)
    return scores


def render_zig(scores: list[int], save_sha256: str) -> str:
    if len(save_sha256) != 64 or any(c not in "0123456789abcdef" for c in save_sha256):
        raise ChokepointDataError("save sha must be 64 lowercase hex characters")
    if not 1 <= len(scores) <= 65535:
        raise ChokepointDataError(f"score count {len(scores)} is outside 1..65535")
    for i, score in enumerate(scores):
        if isinstance(score, bool) or not isinstance(score, int) or not 0 <= score <= 65535:
            raise ChokepointDataError(f"score[{i}] = {score!r} is outside u16")

    out = [
        "// Generated by scripts/chokepoints_emit.py; do not edit by hand.",
        "// Source: evidence/xrefs/chokepoint_scores_4_4_4.tsv",
        "// Scores are save-local; SAVE_SHA256 names the campaign they belong to.",
        "",
        f"pub const SCORE_COUNT: usize = {len(scores)};",
        f"pub const TIER1_MIN: u16 = {TIER1_MIN};",
        f"pub const TIER2_MIN: u16 = {TIER2_MIN};",
        f'pub const SAVE_SHA256: []const u8 = "{save_sha256}";',
        "",
        "pub const scores: [SCORE_COUNT]u16 = .{",
    ]
    rows = [scores[i : i + SCORES_PER_LINE] for i in range(0, len(scores), SCORES_PER_LINE)]
    if len(rows) == 1:
        out.append("    " + ", ".join(str(v) for v in rows[0]) + ",")
    else:
        # zig fmt aligns a multi-row array literal column-wise; emit exactly
        # that layout so `zig fmt --check` stays green without running zig.
        widths = [
            max(len(str(row[j])) for row in rows if j < len(row))
            for j in range(SCORES_PER_LINE)
        ]
        for row in rows:
            cells = [f"{v},".ljust(widths[j] + 2) for j, v in enumerate(row)]
            out.append(("    " + "".join(cells)).rstrip())
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tsv", required=True, help="seven-column score TSV")
    parser.add_argument("--out", required=True, help="Zig file to write or check")
    parser.add_argument("--save-sha", required=True, help="sha256 of the campaign save")
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    args = parser.parse_args(argv)

    try:
        text = pathlib.Path(args.tsv).read_text(encoding="utf-8")
        rendered = render_zig(parse_scores(text), args.save_sha)
    except (OSError, UnicodeDecodeError, ChokepointDataError) as exc:
        print(f"chokepoints_emit: {exc}", file=sys.stderr)
        return 2

    out = pathlib.Path(args.out)
    if args.check:
        try:
            existing = out.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"chokepoints_emit: {out} cannot be read for --check: {exc}", file=sys.stderr)
            return 2
        if existing != rendered:
            print(
                f"chokepoints_emit: {out} drifted from {args.tsv}; regenerate it",
                file=sys.stderr,
            )
            return 2
        return 0

    try:
        out.write_text(rendered, encoding="utf-8")
    except OSError as exc:
        print(f"chokepoints_emit: cannot write {out}: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
